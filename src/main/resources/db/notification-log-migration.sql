-- Run once against the existing database before starting the updated application.

ALTER TABLE NOTIFICATION_LOG
    ADD COLUMN IF NOT EXISTS STATUS VARCHAR(20);

ALTER TABLE NOTIFICATION_LOG
    ALTER COLUMN REASON VARCHAR(50);

UPDATE NOTIFICATION_LOG
SET STATUS = CASE
    WHEN OUTCOME = 'SENT' THEN 'SENT'
    ELSE 'FAILED'
END,
    REASON = CASE
        WHEN OUTCOME = 'SENT' THEN 'OK'
        WHEN OUTCOME = 'GATEWAY_TIMEOUT' THEN 'GATEWAY_TIMEOUT'
        WHEN OUTCOME = 'INVALID_CONTACT' THEN 'INVALID_CONTACT'
        ELSE 'INTERNAL_SERVER_ERROR'
    END;

UPDATE NOTIFICATION_LOG
SET REASON = CASE REASON
    WHEN 'OKAY' THEN 'OK'
    WHEN '0' THEN 'OK'
    WHEN '1' THEN 'GATEWAY_TIMEOUT'
    WHEN '2' THEN 'INVALID_CONTACT'
    WHEN '3' THEN 'INTERNAL_SERVER_ERROR'
    ELSE REASON
END;

ALTER TABLE REMINDER_DLQ
    ADD COLUMN IF NOT EXISTS STATUS VARCHAR(20);

ALTER TABLE REMINDER_DLQ
    ALTER COLUMN LAST_ERROR VARCHAR(50);

UPDATE REMINDER_DLQ
SET STATUS = 'FAILED',
    LAST_ERROR = CASE
        WHEN LAST_ERROR = 'OKAY' THEN 'OK'
        WHEN LAST_ERROR = 'GATEWAY_TIMEOUT' THEN 'GATEWAY_TIMEOUT'
        WHEN LAST_ERROR = 'INVALID_CONTACT' THEN 'INVALID_CONTACT'
        ELSE 'INTERNAL_SERVER_ERROR'
    END;

ALTER TABLE NOTIFICATION_LOG
    DROP COLUMN IF EXISTS OUTCOME;
